import { fireEvent, render, screen } from '@testing-library/react-native';
import { ScalePanel } from '../src/auth/ScalePanel';
import type { ScaleActions } from '../src/auth/scale';
import type { ScaleSlot, ScaleView } from '../src/auth/scale-state';
const actor = '00000000-0000-4000-8000-000000000001';
const slot: ScaleSlot = { id: '00000000-0000-4000-8000-000000000010', coupleId: '00000000-0000-4000-8000-000000000099', authorId: actor, membershipEpoch: 1, localDate: '2026-01-01', timezone: 'UTC', version: 1, createdAt: '2026-01-01T00:00:00.000Z', state: 'active', value: 0 };
const removed: ScaleSlot = { id: slot.id, coupleId: slot.coupleId, authorId: actor, membershipEpoch: 1, localDate: slot.localDate, timezone: slot.timezone, version: 2, createdAt: slot.createdAt, state: 'removed' };
const base: ScaleView = { userId: actor, available: true, busy: false, checked: false, checkedAt: null, slots: [], ownUsed: 0, capacityPerAuthor: 100, create: { expectedDate: '', timezone: '', value: '' }, editor: null, pending: false, requiresRefresh: false, error: false, status: 'idle' };
function fixture() {
    let view = base;
    const controller = { getSnapshot: () => view, subscribe: jest.fn(() => () => { }), load: jest.fn(async () => { }), setCreateField: jest.fn(), cancelCreate: jest.fn(), create: jest.fn(async () => { }), beginEdit: jest.fn(), setValue: jest.fn(), cancelEdit: jest.fn(), save: jest.fn(async () => { }), remove: jest.fn(async () => { }), retry: jest.fn(async () => { }) } satisfies ScaleActions;
    return { controller, set: (next: ScaleView) => { view = next; } };
}
it.each(['ru', 'en'] as const)('explicit shared scale, zero vs blank, author-only edits and confirmations %s', locale => {
    const f = fixture(), props = { controller: f.controller, locale };
    f.set({ ...base, available: false });
    const ui = render(<ScalePanel {...props}/>);
    expect(ui.toJSON()).toBeNull();
    const update = (next: ScaleView) => { f.set(next); ui.rerender(<ScalePanel {...props}/>); };
    update({ ...base, checked: true, checkedAt: slot.createdAt });
    const labels = locale === 'ru' ? ['Ожидаемая сегодняшняя дата YYYY-MM-DD', 'Часовой пояс IANA', 'Новое значение от 0 до 100'] : ['Expected today date YYYY-MM-DD', 'IANA time zone', 'New value from 0 to 100'];
    for (const label of labels)
        expect(screen.getByLabelText(label).props.value).toBe('');
    expect(screen.queryByDisplayValue('50')).toBeNull();
    labels.forEach((label, index) => fireEvent.changeText(screen.getByLabelText(label), [slot.localDate, 'UTC', '0'][index]));
    expect(f.controller.setCreateField.mock.calls).toEqual([['expectedDate', slot.localDate], ['timezone', 'UTC'], ['value', '0']]);
    // Invalid 1000 must reach validation, never be truncated into a valid 100.
    expect(screen.getByLabelText(labels[2]).props.maxLength).toBeGreaterThan(3);
    fireEvent.changeText(screen.getByLabelText(labels[2]), '1000');
    expect(f.controller.setCreateField).toHaveBeenLastCalledWith('value', '1000');
    for (const label of locale === 'ru' ? ['Поделиться оценкой за сегодня', 'Отменить новую оценку', 'Обновить всю историю'] : ['Share today’s rating', 'Cancel new rating', 'Refresh entire history'])
        fireEvent.press(screen.getByText(label));
    expect(f.controller.create).toHaveBeenCalledTimes(1);
    expect(f.controller.cancelCreate).toHaveBeenCalledTimes(1);
    expect(f.controller.load).toHaveBeenCalledTimes(1);
    update({ ...base, slots: [slot, { ...slot, id: 'partner', authorId: 'partner', value: 75 }], ownUsed: 1, editor: { id: slot.id, version: 1, mode: 'edit', value: '0' } });
    expect(screen.getByText('0')).toBeTruthy();
    expect(screen.getByText('75')).toBeTruthy();
    expect(screen.getByText(locale === 'ru' ? 'Автор: Партнёр' : 'Author: Partner')).toBeTruthy();
    expect(screen.queryByText(locale === 'ru' ? 'Исправить свою оценку 2' : 'Correct your rating 2')).toBeNull();
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Исправить свою оценку 1' : 'Correct your rating 1'));
    expect(f.controller.beginEdit).toHaveBeenCalledWith(slot.id);
    fireEvent.changeText(screen.getByLabelText(locale === 'ru' ? 'Исправленное значение от 0 до 100' : 'Corrected value from 0 to 100'), '10');
    expect(f.controller.setValue).toHaveBeenCalledWith('10');
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Сохранить исправление для обоих' : 'Save correction for both'));
    expect(f.controller.save).toHaveBeenCalledWith(false);
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Отменить изменение' : 'Cancel change'));
    expect(f.controller.cancelEdit).toHaveBeenCalledTimes(1);
    const remove = locale === 'ru' ? 'Снять свою публикацию 1' : 'Remove your publication 1';
    fireEvent.press(screen.getByText(remove));
    expect(f.controller.remove).not.toHaveBeenCalled();
    expect(screen.getByText(locale === 'ru' ? 'Снять эту оценку с общего просмотра? Уже прочитанные или сохранённые партнёром копии не исчезнут. Дата и пояс записи останутся видны.' : 'Remove this rating from shared view? Copies already read or saved by your partner will not disappear. The entry’s date and zone will remain visible.')).toBeTruthy();
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Не подтверждать' : 'Do not confirm'));
    expect(f.controller.remove).not.toHaveBeenCalled();
    fireEvent.press(screen.getByText(remove));
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Подтвердить снятие' : 'Confirm removal'));
    expect(f.controller.remove).toHaveBeenCalledWith(slot.id, true);
    update({ ...base, slots: [removed], ownUsed: 1, editor: { id: slot.id, version: 2, mode: 'reshare', value: '' } });
    expect(screen.getByLabelText(locale === 'ru' ? 'Значение новой публикации от 0 до 100' : 'New publication value from 0 to 100').props.value).toBe('');
    expect(screen.queryByText('0')).toBeNull();
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Ввести новую публикацию 1' : 'Enter a new publication 1'));
    expect(f.controller.beginEdit).toHaveBeenCalledTimes(2);
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Поделиться заново' : 'Share anew'));
    expect(f.controller.save).toHaveBeenCalledTimes(1);
    expect(screen.getByText(locale === 'ru' ? 'Опубликовать введённое значение заново для обоих? Это новая публикация, не восстановление прежнего значения.' : 'Publish the entered value anew for both? This is a new publication, not restoration of the previous value.')).toBeTruthy();
    update({ ...base, slots: [removed], ownUsed: 1, editor: { id: slot.id, version: 2, mode: 'reshare', value: '44' } });
    expect(screen.getByText(locale === 'ru' ? 'Сейчас введено: 44' : 'Currently entered: 44')).toBeTruthy();
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Подтвердить новую публикацию' : 'Confirm new publication'));
    expect(f.controller.save).toHaveBeenLastCalledWith(true);
    update({ ...base, pending: true, error: true, status: 'retry' });
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Повторить ту же команду' : 'Retry same command'));
    expect(f.controller.retry).toHaveBeenCalledTimes(1);
    fireEvent.changeText(screen.getByLabelText(labels[2]), '25');
    expect(f.controller.setCreateField).toHaveBeenLastCalledWith('value', '25');
    update({ ...base, busy: true, requiresRefresh: true, status: 'saving' });
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Обновить всю историю' : 'Refresh entire history'));
    expect(f.controller.load).toHaveBeenCalledTimes(1);
    for (const status of ['saved', 'invalid', 'conflict', 'unavailable', 'limit', 'dateMismatch'] as const)
        update({ ...base, status });
});
it.each(['ru', 'en'] as const)('at cap correction/reshare remain possible, stale editors are explicit and not saveable %s', locale => {
    const f = fixture(), props = { controller: f.controller, locale };
    const ui = render(<ScalePanel {...props}/>);
    const update = (next: ScaleView) => { f.set(next); ui.rerender(<ScalePanel {...props}/>); };
    update({ ...base, slots: [slot], ownUsed: 100, editor: { id: slot.id, version: 1, mode: 'edit', value: '12' } });
    expect(screen.getByText(locale === 'ru' ? 'Ваших мест осталось по известным данным: 0' : 'Your remaining capacity in known data: 0')).toBeTruthy();
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Поделиться оценкой за сегодня' : 'Share today’s rating'));
    expect(f.controller.create).not.toHaveBeenCalled();
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Сохранить исправление для обоих' : 'Save correction for both'));
    expect(f.controller.save).toHaveBeenCalledTimes(1);
    update({ ...base, slots: [removed], ownUsed: 100, editor: { id: removed.id, version: 2, mode: 'reshare', value: '33' } });
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Поделиться заново' : 'Share anew'));
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Подтвердить новую публикацию' : 'Confirm new publication'));
    expect(f.controller.save).toHaveBeenLastCalledWith(true);
    for (const mode of ['edit', 'reshare'] as const) {
        update({ ...base, slots: [mode === 'edit' ? slot : removed], editor: { id: slot.id, version: mode === 'edit' ? 1 : 2, mode, value: 'Unsaved', stale: true } });
        expect(screen.getByText(new RegExp(locale === 'ru' ? 'Запись изменилась. Несохранённое значение' : 'This entry changed. Your unsaved value'))).toBeTruthy();
        fireEvent.press(screen.getByText(mode === 'edit' ? (locale === 'ru' ? 'Сохранить исправление для обоих' : 'Save correction for both') : (locale === 'ru' ? 'Поделиться заново' : 'Share anew')));
        expect(f.controller.save).toHaveBeenCalledTimes(2);
        fireEvent.changeText(screen.getByDisplayValue('Unsaved'), '42');
        expect(f.controller.setValue).toHaveBeenLastCalledWith('42');
        fireEvent.press(screen.getByText(locale === 'ru' ? 'Отменить изменение' : 'Cancel change'));
    }
    expect(f.controller.cancelEdit).toHaveBeenCalledTimes(2);
});
it('confirmation follows canonical version, actor and removed state; pending blocks actions', () => {
    const f = fixture(), props = { controller: f.controller, locale: 'en' as const };
    f.set({ ...base, slots: [slot] });
    const ui = render(<ScalePanel {...props}/>);
    const update = (next: ScaleView) => { f.set(next); ui.rerender(<ScalePanel {...props}/>); };
    fireEvent.press(screen.getByText('Remove your publication 1'));
    update({ ...base, slots: [removed] });
    expect(screen.queryByText('Confirm removal')).toBeNull();
    expect(screen.queryByText('0')).toBeNull();
    update({ ...base, slots: [slot] });
    fireEvent.press(screen.getByText('Remove your publication 1'));
    update({ ...base, slots: [slot], userId: 'other' });
    expect(screen.queryByText('Confirm removal')).toBeNull();
    update({ ...base, slots: [removed], editor: { id: slot.id, version: 2, mode: 'reshare', value: '10' } });
    fireEvent.press(screen.getByText('Share anew'));
    update({ ...base, slots: [{ ...slot, version: 3, value: 17 }], editor: { id: slot.id, version: 2, mode: 'reshare', value: '10', stale: true } });
    expect(screen.queryByText('Confirm new publication')).toBeNull();
    update({ ...base, slots: [slot], busy: true, pending: true, editor: { id: 'missing', version: 1, mode: 'edit', value: '11' } });
    fireEvent.press(screen.getByText('Correct your rating 1'));
    fireEvent.press(screen.getByText('Remove your publication 1'));
    fireEvent.press(screen.getByText('Save correction for both'));
    expect(f.controller.beginEdit).not.toHaveBeenCalled();
    expect(f.controller.save).not.toHaveBeenCalled();
});
