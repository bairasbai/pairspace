import { journalFixture, journalScope, latch } from './journal-fixture';
import type { JournalPort } from '../src/chat/journal/types';
async function bind(engine: JournalPort) { const result = await engine.bindVerifiedScope(journalScope); if (!result.ok)
    throw Error(result.error); return result.value; }
const draft = (revision: number, text = 'Private draft', replyToId?: string) => ({ revision, text, ...(replyToId ? { replyToId } : {}) });
const pending = (draftRevision: number, body = 'Private draft', clientId = 'command-1', replyToId?: string) => ({ draftRevision, body, clientId, ...(replyToId ? { replyToId } : {}) });
it('commits encrypted full Unicode draft and exact pending, preserves newer revision, removes only matching pending', async () => {
    const f = journalFixture(), j = f.engine(), t = await bind(j), text = '🙂'.repeat(8000);
    expect(await j.inspect(t)).toEqual({ ok: true, value: { hasDraft: false, hasPending: false, draftRevision: -1 } });
    expect(await j.saveDraft(t, draft(0, text, 'target-1'))).toEqual({ ok: true, value: null });
    expect(JSON.stringify(f.row)).not.toContain('🙂');
    expect(JSON.stringify(f.row)).not.toContain('target-1');
    expect(await j.restore(t)).toEqual({ ok: true, value: { draft: draft(0, text, 'target-1'), pending: null } });
    expect(await j.prepareSend(t, pending(0, text, 'command-1', 'target-1'))).toEqual({ ok: true, value: null });
    expect(await j.prepareSend(t, pending(0, text, 'command-1', 'target-1'))).toEqual({ ok: true, value: null });
    expect(await j.saveDraft(t, draft(0, text, 'target-1'))).toEqual({ ok: false, error: 'conflict' });
    expect(await j.saveDraft(t, draft(1, 'Newer'))).toEqual({ ok: true, value: null });
    expect(await j.settlePending(t, 'wrong', 0)).toEqual({ ok: false, error: 'conflict' });
    expect(await j.settlePending(t, 'command-1', 0)).toEqual({ ok: true, value: null });
    expect(await j.restore(t)).toEqual({ ok: true, value: { draft: draft(1, 'Newer'), pending: null } });
    expect(await j.prepareSend(t, pending(0, text, 'command-1', 'target-1'))).toEqual({ ok: false, error: 'stale' });
    expect(await j.settlePending(t, 'command-1', 0)).toEqual({ ok: true, value: null });
    expect(await j.saveDraft(t, draft(1, 'Newer'))).toEqual({ ok: true, value: null });
    expect(await j.saveDraft(t, draft(0, 'Old'))).toEqual({ ok: false, error: 'stale' });
    expect(await j.saveDraft(t, draft(1, 'Changed'))).toEqual({ ok: false, error: 'conflict' });
    expect(await j.prepareSend(t, pending(1, 'Wrong'))).toEqual({ ok: false, error: 'conflict' });
    expect(await j.prepareSend(t, pending(1, 'Newer', 'command-2'))).toEqual({ ok: true, value: null });
    expect(await j.prepareSend(t, pending(2, 'Other', 'command-3'))).toEqual({ ok: false, error: 'conflict' });
    expect(await j.discardPending(t, 'command-2', 1)).toEqual({ ok: true, value: null });
    expect(await j.restore(t)).toEqual({ ok: true, value: { draft: null, pending: null } });
});
it('restart requires verified bind and explicit restore; leases reject old engines, suspend retains encrypted journal', async () => {
    const f = journalFixture(), a = f.engine(), ta = await bind(a);
    await a.saveDraft(ta, draft(2, 'Pending'));
    await a.prepareSend(ta, pending(2, 'Pending'));
    await a.saveDraft(ta, draft(3, 'New unsent'));
    const b = f.engine(), tb = await bind(b);
    expect(await a.saveDraft(ta, draft(4, 'Late'))).toEqual({ ok: false, error: 'stale' });
    expect(await b.inspect(tb)).toEqual({ ok: true, value: { hasDraft: true, hasPending: true, draftRevision: 3 } });
    expect(await b.restore(tb)).toEqual({ ok: true, value: { draft: draft(3, 'New unsent'), pending: pending(2, 'Pending') } });
    const before = f.row;
    b.suspend(tb);
    expect(await b.restore(tb)).toEqual({ ok: false, error: 'stale' });
    expect(f.row).toEqual(before);
    const next = await bind(b);
    b.suspend(tb);
    expect((await b.restore(next)).ok).toBe(true);
    expect(await b.retire(tb)).toEqual({ ok: false, error: 'stale' });
    expect((await b.inspect(next)).ok).toBe(true);
});
it('retirement fences encryption in flight, clears durably before key deletion and rotates on next bind', async () => {
    const f = journalFixture(), j = f.engine(), t = await bind(j), gate = latch();
    const oldKey = f.key;
    f.onSeal(async () => { gate.arrive(); await gate.gate; });
    const write = j.saveDraft(t, draft(1));
    await gate.reached;
    const retire = j.retire(t);
    gate.release();
    expect(await write).toEqual({ ok: false, error: 'stale' });
    expect(await retire).toEqual({ ok: true, value: null });
    expect(f.row?.scope).toBeNull();
    expect(f.row?.sealed).toBeNull();
    expect(f.key).toBeNull();
    f.onSeal(null);
    const next = await bind(j);
    expect(next.installationId).not.toBe(t.installationId);
    expect(f.key?.secret).not.toBe(oldKey?.secret);
    await j.saveDraft(next, draft(1));
    f.failRemove();
    expect(await j.retire(next)).toEqual({ ok: false, error: 'storage_error' });
    expect(f.row?.scope).toBeNull();
    expect((await j.bindVerifiedScope(journalScope))).toEqual({ ok: false, error: 'locked' });
    f.failRemove(false);
    expect(await j.reset()).toEqual({ ok: true, value: null });
    expect((await j.bindVerifiedScope(journalScope)).ok).toBe(true);
});
it('failures and lost commit ACK never become success, missing key/cipher corruption never silently overwrite', async () => {
    const f = journalFixture(), j = f.engine(), t = await bind(j);
    await j.saveDraft(t, draft(1));
    const before = f.row;
    f.failWrite();
    expect(await j.prepareSend(t, pending(1))).toEqual({ ok: false, error: 'storage_error' });
    expect(f.row).toEqual(before);
    f.failAfterCommit();
    expect(await j.prepareSend(t, pending(1))).toEqual({ ok: false, error: 'storage_error' });
    expect(await j.prepareSend(t, pending(1))).toEqual({ ok: true, value: null });
    const good = f.row!, key = f.key;
    f.key = null;
    expect(await j.restore(t)).toEqual({ ok: false, error: 'locked' });
    expect(await j.bindVerifiedScope(journalScope)).toEqual({ ok: false, error: 'locked' });
    expect(f.row).toEqual(good);
    f.key = key;
    f.row = { ...good, sealed: { data: 'AAAA' } };
    expect(await j.restore(t)).toEqual({ ok: false, error: 'corrupt' });
    expect(await j.saveDraft(t, draft(2))).toEqual({ ok: false, error: 'corrupt' });
    f.row = { ...good, generation: good.generation + 1 };
    expect(await j.restore(t)).toEqual({ ok: false, error: 'stale' });
    f.row = good;
    expect(await j.reset()).toEqual({ ok: true, value: null });
    const orphan = journalFixture();
    orphan.failWrite();
    expect(await orphan.engine().bindVerifiedScope(journalScope)).toEqual({ ok: false, error: 'storage_error' });
    expect(orphan.row).toBeNull();
    expect(orphan.key).not.toBeNull();
    const repair = orphan.engine();
    expect(await repair.bindVerifiedScope(journalScope)).toEqual({ ok: false, error: 'locked' });
    expect(await repair.reset()).toEqual({ ok: true, value: null });
    expect((await repair.bindVerifiedScope(journalScope)).ok).toBe(true);
});
it('scope retirement is explicit in verified binding; invalid inputs do not replace stored data', async () => {
    const f = journalFixture(), j = f.engine(), t = await bind(j);
    await j.saveDraft(t, draft(4));
    const oldKey = f.key;
    const changed = await j.bindVerifiedScope({ ...journalScope, coupleId: 'pair-2', membershipEpoch: 2 });
    expect(changed.ok).toBe(true);
    if (!changed.ok)
        throw Error('bind');
    expect(f.key?.secret).not.toBe(oldKey?.secret);
    expect(await j.restore(changed.value)).toEqual({ ok: true, value: { draft: null, pending: null } });
    expect(await j.restore(t)).toEqual({ ok: false, error: 'stale' });
    for (const input of [{ ...journalScope, origin: 'http://evil.test' }, { ...journalScope, origin: 'garbage' }, { ...journalScope, userId: '' }, { ...journalScope, membershipEpoch: 0 }])
        expect(await j.bindVerifiedScope(input)).toEqual({ ok: false, error: 'invalid' });
    expect(await j.saveDraft(changed.value, draft(1, 'x'.repeat(8001)))).toEqual({ ok: false, error: 'invalid' });
    expect(await j.saveDraft(changed.value, draft(1, '\ud800'))).toEqual({ ok: false, error: 'invalid' });
    expect(await j.saveDraft(changed.value, draft(1, ' \r\n '))).toEqual({ ok: true, value: null });
    expect(await j.prepareSend(changed.value, pending(1, ' '))).toEqual({ ok: false, error: 'invalid' });
    expect(await j.discardPending(changed.value, '', 0)).toEqual({ ok: false, error: 'invalid' });
});
it('atomically discards pre-prepare attempts, fences late writes, and preserves unrelated drafts', async () => {
    const f = journalFixture(), j = f.engine(), t = await bind(j);
    await j.saveDraft(t, draft(1));
    expect(await j.discardPending(t, null, 1)).toEqual({ ok: true, value: null });
    expect(await j.restore(t)).toEqual({ ok: true, value: { draft: null, pending: null } });
    expect(await j.saveDraft(t, draft(1))).toEqual({ ok: false, error: 'conflict' });
    expect(await j.prepareSend(t, pending(1))).toEqual({ ok: false, error: 'stale' });
    const row = f.row;
    expect(await j.discardPending(t, null, 1)).toEqual({ ok: true, value: null });
    expect(f.row).toEqual(row);
    await j.saveDraft(t, draft(3, 'Newer'));
    await j.discardPending(t, null, 2);
    expect(await j.restore(t)).toEqual({ ok: true, value: { draft: draft(3, 'Newer'), pending: null } });
    await j.prepareSend(t, pending(3, 'Newer'));
    expect(await j.discardPending(t, null, 3)).toEqual({ ok: false, error: 'conflict' });
    expect(await j.discardPending(t, 'command-1', 2)).toEqual({ ok: false, error: 'conflict' });
    await j.saveDraft(t, draft(4, 'Keep'));
    f.failCommit();
    expect(await j.discardPending(t, 'command-1', 3)).toEqual({ ok: false, error: 'storage_error' });
    expect((await j.inspect(t))).toMatchObject({ ok: true, value: { hasPending: true, hasDraft: true } });
    expect(await j.discardPending(t, 'command-1', 3)).toEqual({ ok: true, value: null });
    expect(await j.restore(t)).toEqual({ ok: true, value: { draft: draft(4, 'Keep'), pending: null } });
    // Advancing a discard floor never deletes a nonmatching older draft either.
    await j.discardPending(t, null, 5);
    expect(await j.restore(t)).toEqual({ ok: true, value: { draft: draft(4, 'Keep'), pending: null } });
    expect(await j.saveDraft(t, draft(4, 'Old late save'))).toEqual({ ok: false, error: 'stale' });
    expect(await j.discardPending(t, '', 5)).toEqual({ ok: false, error: 'invalid' });
    expect(await j.discardPending(t, null, -1)).toEqual({ ok: false, error: 'invalid' });
});
