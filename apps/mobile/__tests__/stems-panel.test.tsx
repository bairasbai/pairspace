import { fireEvent, render, screen } from '@testing-library/react-native';
import { StemsPanel } from '../src/auth/StemsPanel';
import type { StemsActions } from '../src/auth/stems';
import type { StemRound, StemView } from '../src/auth/stems-state';
const actor = '00000000-0000-4000-8000-000000000001', partner = '00000000-0000-4000-8000-000000000002';
const round: StemRound = { id: '00000000-0000-4000-8000-000000000010', coupleId: '00000000-0000-4000-8000-000000000099', authorId: partner, recipientId: actor, membershipEpoch: 1, sequence: 1, version: 1, createdAt: '2026-01-01T00:00:00.000Z', phase: 'waiting', authorTextState: 'active', recipientTextState: 'absent', beginning: 'Synthetic beginning' };
const base: StemView = { userId: actor, available: true, busy: false, checked: false, checkedAt: null, rounds: [], used: 0, capacity: 100, create: { beginning: '', ownContinuation: '' }, completionDraft: null, pending: false, requiresRefresh: false, error: false, status: 'idle' };
function fixture() {
    let view = base;
    const controller = { getSnapshot: () => view, subscribe: jest.fn(() => () => { }), load: jest.fn(async () => { }), retry: jest.fn(async () => { }), create: jest.fn(async () => { }), complete: jest.fn(async () => { }), skip: jest.fn(async () => { }), removeAuthorBundle: jest.fn(async () => { }), removeRecipientContinuation: jest.fn(async () => { }), setCreate: jest.fn(), setContinuation: jest.fn(), beginComplete: jest.fn(), cancelCreate: jest.fn(), cancelComplete: jest.fn() } satisfies StemsActions;
    return { controller, set: (next: StemView) => { view = next; } };
}
it.each(['ru', 'en'] as const)('explicit create/complete/skip/removal confirmation and attribution %s', locale => {
    const f = fixture(), props = { controller: f.controller, locale };
    f.set({ ...base, available: false });
    const ui = render(<StemsPanel {...props}/>);
    expect(ui.toJSON()).toBeNull();
    const update = (next: StemView) => { f.set(next); ui.rerender(<StemsPanel {...props}/>); };
    update({ ...base, checked: true, checkedAt: round.createdAt });
    expect(screen.getByText(locale === 'ru' ? 'В проверенном списке пока нет фраз.' : 'No phrases in the checked list yet.')).toBeTruthy();
    fireEvent.changeText(screen.getByLabelText(locale === 'ru' ? 'Начало фразы (1–500 символов)' : 'Phrase beginning (1–500 characters)'), 'Beginning');
    fireEvent.changeText(screen.getByLabelText(locale === 'ru' ? 'Ваше продолжение (1–2000 символов)' : 'Your continuation (1–2000 characters)'), 'Committed own text');
    expect(f.controller.setCreate.mock.calls).toEqual([['beginning', 'Beginning'], ['ownContinuation', 'Committed own text']]);
    update({ ...base, create: { beginning: 'Beginning', ownContinuation: 'Committed own text' } });
    const confirm = locale === 'ru' ? 'Подтвердить' : 'Confirm';
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Предложить фразу' : 'Offer a phrase'));
    expect(f.controller.create).not.toHaveBeenCalled();
    expect(screen.getByText(locale === 'ru' ? 'Начало станет видно партнёру сейчас. Ваше продолжение будет скрыто от партнёра, пока он не отправит своё; затем оба продолжения станут общими. Изменить отправленные тексты нельзя, но свой набор текстов можно удалить.' : 'The beginning becomes visible to your partner now. Your continuation stays hidden from them until they submit theirs; then both continuations are shared. Submitted texts cannot be edited, but you can remove your own text bundle.')).toBeTruthy();
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Не подтверждать' : 'Do not confirm'));
    expect(f.controller.create).not.toHaveBeenCalled();
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Предложить фразу' : 'Offer a phrase'));
    fireEvent.press(screen.getByText(confirm));
    expect(f.controller.create).toHaveBeenCalledWith(true);
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Отменить новую фразу' : 'Cancel new phrase'));
    expect(f.controller.cancelCreate).toHaveBeenCalledTimes(1);
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Обновить все фразы' : 'Refresh all phrases'));
    expect(f.controller.load).toHaveBeenCalledTimes(1);
    update({ ...base, rounds: [round], used: 1, completionDraft: { id: round.id, version: 1, text: 'Current draft' } });
    expect(screen.getByText(locale === 'ru' ? 'Автор начала: Партнёр' : 'Beginning by: Partner')).toBeTruthy();
    expect(screen.getByText(locale === 'ru' ? 'Продолжает: Вы' : 'Continuation by: You')).toBeTruthy();
    expect(screen.getByText(locale === 'ru' ? 'Продолжение автора скрыто от вас до вашего ответа. Пропуск его не раскроет.' : 'The author’s continuation is hidden from you until you submit yours. Skipping will not reveal it.')).toBeTruthy();
    update({ ...base, rounds: [{ ...round, phase: 'skipped', version: 2 }] });
    expect(screen.getByText(locale === 'ru' ? 'Фраза пропущена: продолжение автора останется скрытым от вас и больше не раскроется.' : 'This phrase was skipped: the author’s continuation will remain hidden from you permanently.')).toBeTruthy();
    expect(screen.queryByText(locale === 'ru' ? 'Продолжить 1' : 'Continue 1')).toBeNull();
    update({ ...base, rounds: [round], used: 1, completionDraft: { id: round.id, version: 1, text: 'Current draft' } });
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Продолжить 1' : 'Continue 1'));
    expect(f.controller.beginComplete).toHaveBeenCalledWith(round.id);
    fireEvent.changeText(screen.getByLabelText(locale === 'ru' ? 'Ваш несохранённый ответ (1–2000 символов)' : 'Your unsaved response (1–2000 characters)'), 'Newer draft');
    expect(f.controller.setContinuation).toHaveBeenCalledWith('Newer draft');
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Опубликовать продолжение' : 'Publish continuation'));
    expect(f.controller.complete).not.toHaveBeenCalled();
    fireEvent.press(screen.getByText(confirm));
    expect(f.controller.complete).toHaveBeenCalledWith(true);
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Отменить ответ' : 'Cancel response'));
    expect(f.controller.cancelComplete).toHaveBeenCalledTimes(1);
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Пропустить 1' : 'Skip 1'));
    expect(f.controller.skip).not.toHaveBeenCalled();
    expect(screen.getByText(locale === 'ru' ? 'Пропустить без объяснения? Это окончательно. Продолжение автора не раскроется, свой ответ добавить уже нельзя.' : 'Skip without an explanation? This is final. The author’s continuation will not be revealed, and you cannot add your own later.')).toBeTruthy();
    fireEvent.press(screen.getByText(confirm));
    expect(f.controller.skip).toHaveBeenCalledWith(round.id, true);
    const completed = { ...round, phase: 'completed' as const, version: 2, authorContinuation: 'Author revealed', recipientTextState: 'active' as const, recipientContinuation: 'Recipient shared', completedAt: round.createdAt };
    update({ ...base, rounds: [completed] });
    expect(screen.getByText('Author revealed')).toBeTruthy();
    expect(screen.getByText('Recipient shared')).toBeTruthy();
    expect(screen.getByText(locale === 'ru' ? 'Не раньше даты фразы; не отметка прочтения.' : 'Not before the phrase date; not a read receipt.')).toBeTruthy();
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Удалить своё продолжение 1' : 'Remove your continuation 1'));
    expect(screen.getByText(locale === 'ru' ? 'Удалить только своё продолжение? Оставшиеся тексты автора останутся видимыми. Фраза не закроется заново; заменить ответ нельзя. Уже прочитанные копии не исчезнут.' : 'Remove only your continuation? The author’s remaining texts stay visible. The phrase does not relock; no replacement response is allowed. Already-read copies will not disappear.')).toBeTruthy();
    fireEvent.press(screen.getByText(confirm));
    expect(f.controller.removeRecipientContinuation).toHaveBeenCalledWith(round.id, true);
    update({ ...base, rounds: [{ ...completed, authorId: actor, recipientId: partner }] });
    expect(screen.getByText(locale === 'ru' ? 'Автор начала: Вы' : 'Beginning by: You')).toBeTruthy();
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Удалить свои начало и продолжение 1' : 'Remove your beginning and continuation 1'));
    expect(screen.getByText(locale === 'ru' ? 'Удалить свои начало и продолжение? Ожидающая фраза будет отозвана. При завершённой фразе продолжение партнёра останется видимым; пропущенная останется пропущенной. Уже прочитанные копии не исчезнут.' : 'Remove your beginning and continuation? A waiting phrase will be withdrawn. For a completed phrase, the partner’s continuation remains visible; a skipped phrase stays skipped. Already-read copies will not disappear.')).toBeTruthy();
    fireEvent.press(screen.getByText(confirm));
    expect(f.controller.removeAuthorBundle).toHaveBeenCalledWith(round.id, true);
    update({ ...base, rounds: [{ ...completed, authorTextState: 'removed', beginning: undefined, authorContinuation: undefined, recipientTextState: 'removed', recipientContinuation: undefined, version: 4 }] });
    expect(screen.queryByText('Author revealed')).toBeNull();
    expect(screen.queryByText('Recipient shared')).toBeNull();
    update({ ...base, pending: true, status: 'retry', error: true });
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Повторить ту же команду' : 'Retry same command'));
    expect(f.controller.retry).toHaveBeenCalledTimes(1);
    update({ ...base, busy: true, requiresRefresh: true, status: 'saving' });
    fireEvent.press(screen.getByText(locale === 'ru' ? 'Обновить все фразы' : 'Refresh all phrases'));
    expect(f.controller.load).toHaveBeenCalledTimes(1);
    for (const status of ['idle', 'saved', 'invalid', 'conflict', 'unavailable', 'limit'] as const)
        update({ ...base, status });
});
it.each(['ru', 'en'] as const)('stale draft remains editable and cancellable; cannot publish %s', locale => {
    const f = fixture(), props = { controller: f.controller, locale };
    const ui = render(<StemsPanel {...props}/>);
    for (const stale of ['changed', 'terminal'] as const) {
        f.set({ ...base, rounds: [round], completionDraft: { id: round.id, version: 1, text: 'Unsaved text', stale } });
        ui.rerender(<StemsPanel {...props}/>);
        expect(screen.getByText(new RegExp(locale === 'ru' ? (stale === 'changed' ? 'Фраза изменилась. Несохранённый' : 'Эта фраза больше не принимает продолжение.') : (stale === 'changed' ? 'This phrase changed. Your unsaved' : 'This phrase no longer accepts a continuation.')))).toBeTruthy();
        fireEvent.press(screen.getByText(locale === 'ru' ? 'Опубликовать продолжение' : 'Publish continuation'));
        expect(screen.queryByText(locale === 'ru' ? 'Подтвердить' : 'Confirm')).toBeNull();
        fireEvent.changeText(screen.getByDisplayValue('Unsaved text'), 'Still editable');
        expect(f.controller.setContinuation).toHaveBeenLastCalledWith('Still editable');
        fireEvent.press(screen.getByText(locale === 'ru' ? 'Отменить ответ' : 'Cancel response'));
    }
    expect(f.controller.cancelComplete).toHaveBeenCalledTimes(2);
});
it('recipient never renders hidden author text while waiting/skipped; cap and confirmation scope fences', () => {
    const f = fixture(), props = { controller: f.controller, locale: 'en' as const };
    f.set({ ...base, rounds: [{ ...round, authorContinuation: 'Must remain hidden' }], used: 100 });
    const ui = render(<StemsPanel {...props}/>);
    const update = (next: StemView) => { f.set(next); ui.rerender(<StemsPanel {...props}/>); };
    expect(screen.queryByText('Must remain hidden')).toBeNull();
    fireEvent.press(screen.getByText('Offer a phrase'));
    expect(screen.queryByText('Confirm')).toBeNull();
    fireEvent.press(screen.getByText('Skip 1'));
    fireEvent.press(screen.getByText('Confirm'));
    expect(f.controller.skip).toHaveBeenCalledTimes(1);
    update({ ...base, rounds: [{ ...round, phase: 'skipped', version: 2, authorContinuation: 'Must remain hidden' }] });
    expect(screen.queryByText('Must remain hidden')).toBeNull();
    update({ ...base, rounds: [{ ...round, phase: 'skipped', version: 2, authorId: actor, recipientId: partner, authorContinuation: 'Own committed text' }] });
    expect(screen.getByText('Own committed text')).toBeTruthy();
    fireEvent.press(screen.getByText('Remove your beginning and continuation 1'));
    update({ ...base, rounds: [{ ...round, phase: 'withdrawn', version: 2, authorTextState: 'removed', beginning: undefined }] });
    expect(screen.queryByText('Confirm')).toBeNull();
    expect(screen.queryByText('Own committed text')).toBeNull();
    update({ ...base, rounds: [round] });
    fireEvent.press(screen.getByText('Skip 1'));
    update({ ...base, userId: partner, rounds: [round] });
    expect(screen.queryByText('Confirm')).toBeNull();
    update({ ...base, rounds: [round], completionDraft: { id: round.id, version: 1, text: 'Draft' } });
    fireEvent.press(screen.getByText('Publish continuation'));
    update({ ...base, rounds: [{ ...round, phase: 'skipped', version: 2 }], completionDraft: { id: round.id, version: 1, text: 'Draft', stale: 'terminal' } });
    expect(screen.queryByText('Confirm')).toBeNull();
    update({ ...base });
    fireEvent.press(screen.getByText('Offer a phrase'));
    update({ ...base, used: 100 });
    fireEvent.press(screen.getByText('Confirm'));
    expect(f.controller.create).not.toHaveBeenCalled();
    update({ ...base, busy: true, pending: true, rounds: [round], completionDraft: { id: round.id, version: 1, text: 'Newer RAM' } });
    fireEvent.press(screen.getByText('Continue 1'));
    fireEvent.press(screen.getByText('Publish continuation'));
    expect(f.controller.beginComplete).not.toHaveBeenCalled();
    expect(f.controller.complete).not.toHaveBeenCalled();
    fireEvent.changeText(screen.getByDisplayValue('Newer RAM'), 'New draft');
    expect(f.controller.setContinuation).toHaveBeenCalledWith('New draft');
});
