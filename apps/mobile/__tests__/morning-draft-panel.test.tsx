import { act, fireEvent, render } from '@testing-library/react-native';
import { MorningDraftPanel, draftCopy } from '../src/auth/MorningDraftPanel';
import { draftFixture, draftSlot } from './morning-draft.fixture';
import { slot } from './mornings.fixture';
it.each(['ru', 'en'] as const)('prepared editor actions and honest statuses in %s', async locale => {
  const f = draftFixture(), t = draftCopy[locale], a = f.actions;
  const begin = jest.fn(), save = jest.fn(), reload = jest.fn(), retry = jest.fn(), cancel = jest.fn(), setDraft = jest.fn();
  const actions = { ...a, begin, save, reload, retry, cancel, setDraft };
  const screen = render(<MorningDraftPanel locale={locale} selected={draftSlot()} view={a.getSnapshot()} actions={actions} />);
  fireEvent.press(screen.getByText(t.begin)); expect(begin).toHaveBeenCalledWith(draftSlot());
  await act(async () => { await a.begin(draftSlot()); });
  const view = a.getSnapshot();
  screen.rerender(<MorningDraftPanel locale={locale} selected={null} view={view} actions={actions} />);
  expect(screen.getByText(t.notice)).toBeTruthy();
  fireEvent.changeText(screen.getByLabelText(t.title), 'private'); expect(setDraft).toHaveBeenCalledWith('private');
  fireEvent.press(screen.getByText(t.save)); expect(save).toHaveBeenCalled();
  fireEvent.press(screen.getByText(t.reload)); expect(reload).toHaveBeenCalled();
  fireEvent.press(screen.getByText(t.cancel)); expect(cancel).toHaveBeenCalled();
  screen.rerender(<MorningDraftPanel locale={locale} selected={draftSlot()} view={{ ...view, status: 'unknown', error: 'transport_error' }} actions={actions} />);
  expect(screen.getByText(t.pending)).toBeTruthy(); expect(screen.getByText(t.error)).toBeTruthy();
  fireEvent.press(screen.getByText(t.retry)); expect(retry).toHaveBeenCalled();
  fireEvent.press(screen.getByText(t.save)); expect(save).toHaveBeenCalledTimes(1);
  fireEvent.press(screen.getByText(t.cancel)); expect(cancel).toHaveBeenCalledTimes(1);
  screen.rerender(<MorningDraftPanel locale={locale} selected={slot(10, true)} view={{ ...view, status: 'conflict', draftPreserved: true, error: 'cancel_edit_first' }} actions={actions} />);
  expect(screen.getByText(t.conflict)).toBeTruthy(); expect(screen.getByText(t.preserved)).toBeTruthy(); expect(screen.getByText(t.cancelFirst)).toBeTruthy();
  screen.rerender(<MorningDraftPanel locale={locale} selected={{ ...draftSlot(), state: 'available' }} view={{ ...view, status: 'saved' }} actions={actions} />);
  expect(screen.getByText(t.saved)).toBeTruthy(); expect(screen.queryByText(t.begin)).not.toBeNull();
  screen.rerender(<MorningDraftPanel locale={locale} selected={null} view={{ ...view, available: false }} actions={actions} />);
  expect(screen.queryByText(t.title)).toBeNull();
});
it.each(['ru', 'en'] as const)('explicit removal warning, bound confirmation, terminal and limit in %s', async locale => {
  const f = draftFixture(), a = f.actions, t = draftCopy[locale]; await a.begin(draftSlot());
  const beginDelete = jest.fn(), confirmDelete = jest.fn(), cancelDelete = jest.fn();
  const actions = { ...a, beginDelete, confirmDelete, cancelDelete };
  const view = a.getSnapshot();
  const screen = render(<MorningDraftPanel locale={locale} selected={draftSlot()} view={view} actions={actions} />);
  fireEvent.press(screen.getByText(t.remove)); expect(beginDelete).toHaveBeenCalled();
  screen.rerender(<MorningDraftPanel locale={locale} selected={draftSlot()} view={{ ...view, confirmation: { token: 'token', slotId: draftSlot().id, version: 1 } }} actions={actions} />);
  expect(screen.getByText(t.warning)).toBeTruthy();
  fireEvent.press(screen.getByText(t.confirm)); expect(confirmDelete).toHaveBeenCalledWith('token');
  fireEvent.press(screen.getByText(t.cancelDelete)); expect(cancelDelete).toHaveBeenCalled();
  screen.rerender(<MorningDraftPanel locale={locale} selected={draftSlot()} view={{ ...view, state: 'deleted', status: 'deleted' }} actions={actions} />);
  expect(screen.getByText(t.deleted)).toBeTruthy(); expect(screen.queryByText(t.remove)).toBeNull();
  screen.rerender(<MorningDraftPanel locale={locale} selected={null} view={{ ...view, error: 'terminal_knowledge_limit' }} actions={actions} />);
  expect(screen.getByText(t.limit)).toBeTruthy();
});
