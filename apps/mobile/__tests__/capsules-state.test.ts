import { canReadCapsule, emptyCapsules, mergeCapsule, capsuleOrder } from '../src/auth/capsules-state';
import { provesCapsuleCommand } from '../src/auth/capsules-proof';
import { own, removed, resealed, context, before, due, schedule, uuid } from './capsules-fixtures';
it('only own due body is readable; singleton merge rejects foreign metadata, regressions and identity changes', () => {
 const view = { ...emptyCapsules, userId: context.userId, capsules: [own], used: 1 };
 expect(canReadCapsule(own, context.userId, before)).toBe(false); expect(canReadCapsule(own, context.userId, due)).toBe(true);
 expect(canReadCapsule(own, null, due)).toBe(false); expect(canReadCapsule(own, context.userId, null)).toBe(false);
 expect(canReadCapsule(own, uuid(4), due)).toBe(false); expect(canReadCapsule(removed, context.userId, due)).toBe(false);
 expect(() => mergeCapsule(view, { ...own, authorId: uuid(4) }, due)).toThrow();
 expect(() => mergeCapsule(view, { ...own, id: uuid(11) }, due)).toThrow();
 expect(() => mergeCapsule({ ...view, capsules: [removed] }, own, due)).toThrow();
 const reader = { capsule: own, text: 'Synthetic', checkedAt: due };
 expect(mergeCapsule({ ...view, reader }, own, due).reader).toBe(reader);
 expect(mergeCapsule({ ...view, reader }, removed, due).reader).toBeNull();
 expect(mergeCapsule({ ...view, reader }, resealed, due).reader).toBeNull();
 expect(mergeCapsule({ ...view, reader }, own, before).reader).toBeNull();
 expect(capsuleOrder(own, own)).toBe(0); expect(capsuleOrder(own, { ...own, id: uuid(10) })).toBe(1);
 expect(capsuleOrder({ ...own, id: uuid(10) }, own)).toBe(-1);
 expect(capsuleOrder(own, { ...own, createdAt: due })).toBe(1); expect(capsuleOrder({ ...own, createdAt: due }, own)).toBe(-1);
});
it('receipt proof reconstructs original create schedule, compatible reseal intermediates and terminal remove', () => {
 const command = { kind: 'create' as const, base: null, schedule, floor: before, knownIds: [] };
 expect(provesCapsuleCommand(command, own, false, context)).toBe(true);
 expect(provesCapsuleCommand(command, resealed, true, context)).toBe(true);
 expect(provesCapsuleCommand(command, resealed, false, context)).toBe(false);
 expect(provesCapsuleCommand({ ...command, knownIds: [own.id] }, own, true, context)).toBe(false);
 expect(provesCapsuleCommand({ ...command, floor: due }, own, true, context)).toBe(false);
 expect(provesCapsuleCommand({ ...command, schedule: null }, own, true, context)).toBe(false);
 const reseal = { ...command, kind: 'reseal' as const, base: own, schedule: { ...schedule, localDate: '2026-11-13' } };
 expect(provesCapsuleCommand(reseal, resealed, false, context)).toBe(true);
 const later = { ...resealed, version: 3, sealedAt: '2026-11-12T00:00:00.000Z', localDate: '2026-11-15', releaseAt: '2026-11-15T06:00:00.000Z' };
 expect(provesCapsuleCommand(reseal, later, true, context)).toBe(true);
 expect(provesCapsuleCommand(reseal, { ...later, version: 4, contentState: 'removed' }, true, context)).toBe(true);
 expect(provesCapsuleCommand(reseal, { ...resealed, version: 3, contentState: 'removed' }, true, context)).toBe(true);
 expect(provesCapsuleCommand({ ...reseal, floor: due }, resealed, true, context)).toBe(false);
 expect(provesCapsuleCommand({ ...reseal, floor: null }, resealed, true, context)).toBe(false);
 expect(provesCapsuleCommand({ ...command, kind: 'remove', base: own }, removed, false, context)).toBe(true);
 expect(provesCapsuleCommand({ ...command, kind: 'remove', base: own }, resealed, true, context)).toBe(false);
});
