import { act, fireEvent, render } from '@testing-library/react-native';
import { MorningPreparedPanel, preparedCopy } from '../src/auth/MorningPreparedPanel';
import { preparedFixture, preparedSlot } from './morning-prepared.fixture';
import { slot } from './mornings.fixture';
it.each(['ru', 'en'] as const)('prepared editor actions and honest statuses in %s', async locale => {
  const f = preparedFixture(), t = preparedCopy[locale], a = f.actions;
  const begin = jest.fn(), save = jest.fn(), reload = jest.fn(), retry = jest.fn(), cancel = jest.fn(), setDraft = jest.fn();
  const actions = { ...a, begin, save, reload, retry, cancel, setDraft };
  const screen = render(<MorningPreparedPanel locale={locale} selected={preparedSlot()} view={a.getSnapshot()} actions={actions} />);
  fireEvent.press(screen.getByText(t.begin)); expect(begin).toHaveBeenCalledWith(preparedSlot());
  await act(async () => { await a.begin(preparedSlot()); });
  const view = a.getSnapshot();
  screen.rerender(<MorningPreparedPanel locale={locale} selected={null} view={view} actions={actions} />);
  expect(screen.getByText(t.notice)).toBeTruthy();
  fireEvent.changeText(screen.getByLabelText(t.title), 'private'); expect(setDraft).toHaveBeenCalledWith('private');
  fireEvent.press(screen.getByText(t.save)); expect(save).toHaveBeenCalled();
  fireEvent.press(screen.getByText(t.reload)); expect(reload).toHaveBeenCalled();
  fireEvent.press(screen.getByText(t.cancel)); expect(cancel).toHaveBeenCalled();
  screen.rerender(<MorningPreparedPanel locale={locale} selected={preparedSlot()} view={{ ...view, status: 'unknown', error: 'transport_error' }} actions={actions} />);
  expect(screen.getByText(t.pending)).toBeTruthy(); expect(screen.getByText(t.error)).toBeTruthy();
  fireEvent.press(screen.getByText(t.retry)); expect(retry).toHaveBeenCalled();
  fireEvent.press(screen.getByText(t.save)); expect(save).toHaveBeenCalledTimes(1);
  fireEvent.press(screen.getByText(t.cancel)); expect(cancel).toHaveBeenCalledTimes(1);
  screen.rerender(<MorningPreparedPanel locale={locale} selected={preparedSlot()} view={{ ...view, status: 'closed', needsReload: true }} actions={actions} />);
  expect(screen.getByText(t.closed)).toBeTruthy();
  fireEvent.press(screen.getByText(t.reload)); expect(reload).toHaveBeenCalledTimes(1);
  screen.rerender(<MorningPreparedPanel locale={locale} selected={slot(10, true)} view={{ ...view, status: 'conflict', draftPreserved: true, error: 'cancel_edit_first' }} actions={actions} />);
  expect(screen.getByText(t.conflict)).toBeTruthy(); expect(screen.getByText(t.preserved)).toBeTruthy(); expect(screen.getByText(t.cancelFirst)).toBeTruthy();
  screen.rerender(<MorningPreparedPanel locale={locale} selected={{ ...preparedSlot(), state: 'available' }} view={{ ...view, status: 'saved' }} actions={actions} />);
  expect(screen.getByText(t.saved)).toBeTruthy(); expect(screen.queryByText(t.begin)).toBeNull();
  screen.rerender(<MorningPreparedPanel locale={locale} selected={null} view={{ ...view, available: false }} actions={actions} />);
  expect(screen.queryByText(t.title)).toBeNull();
});
