const session = (port: JournalPort) => fixture(undefined, port);
test('explicit online restoration preserves full 8000 scalar multilingual draft without plaintext storage', async () => {
    const vault = journalFixture(), first = session(vault.engine());
    await first.login();
    const text = '🙂\nя'.repeat(2666) + 'Башҡорт'.slice(0, 2);
    expect([...text]).toHaveLength(8000);
    expect(Buffer.byteLength(text)).toBeGreaterThan(2048);
    first.controller.setDraft(text);
    expect(await first.controller.journal.flush()).toBe(true);
    expect(JSON.stringify(vault.row)).not.toContain(text);
    first.controller.dispose();
    const second = session(vault.engine());
    await second.login();
    expect(second.controller.journal.getSnapshot().status).toBe('recovery');
    expect(second.controller.getSnapshot().draft).toBe('');
    expect(second.post).not.toHaveBeenCalled();
    await second.controller.journal.restore();
    expect(second.controller.getSnapshot().draft).toBe(text);
    expect(second.post).not.toHaveBeenCalled();
    expect(second.controller.journal.getSnapshot().status).toBe('ready');
});
for (const choice of ['current', 'stored'] as const) {
    test(`different private drafts require explicit ${choice} conflict choice and cannot silently overwrite`, async () => {
        const vault = journalFixture(), first = session(vault.engine());
        await first.login();
        first.controller.setDraft('saved private draft');
        await first.controller.journal.flush();
        first.controller.dispose();
        const second = session(vault.engine());
        await second.login();
        const cipher = vault.row!.sealed;
        second.controller.setDraft('new current draft');
        await second.controller.journal.flush();
        expect(vault.row!.sealed).toEqual(cipher);
        await second.controller.journal.restore();
        expect(second.controller.journal.getSnapshot().status).toBe('conflict');
        await second.controller.send();
        expect(second.post).not.toHaveBeenCalled();
        expect(second.controller.getSnapshot().draft).toBe('new current draft');
        expect(vault.row!.sealed).toEqual(cipher);
        const token = second.controller.journal.getSnapshot().conflictToken!;
        await second.controller.journal.resolveConflict('obsolete', choice);
        expect(vault.row!.sealed).toEqual(cipher);
        await second.controller.journal.resolveConflict(token, choice);
        expect(second.controller.getSnapshot().draft).toBe(choice === 'current' ? 'new current draft' : 'saved private draft');
    });
}
test('command is committed durably before POST, crash replay stays metadata-only and keeps stable target/client ID', async () => {
    const vault = journalFixture(), engine = vault.engine(), committed = latch();
    const first = session({ ...engine, async prepareSend(...args) { const result = await engine.prepareSend(...args); committed.arrive(); await committed.gate; return result; } });
    await first.login();
    first.controller.setReplyTarget(message(250).id);
    first.controller.setDraft('original private attempt');
    await first.controller.journal.flush();
    first.post.mockRejectedValueOnce(Error('lost ACK'));
    const sending = first.controller.send();
    await committed.reached;
    expect(vault.row!.hasPending).toBe(true);
    expect(vault.row!.hasDraft).toBe(false);
    expect(first.post).not.toHaveBeenCalled();
    first.controller.setDraft('new independent text');
    await first.controller.journal.flush();
    committed.release();
    await sending;
    const original = await first.post.mock.calls[0][0].clone().json();
    first.controller.dispose();
    const second = session(vault.engine());
    await second.login();
    await second.controller.journal.restore();
    expect(second.controller.getSnapshot().draft).toBe('new independent text');
    expect(second.controller.getSnapshot().outgoing).toBeUndefined();
    expect(JSON.stringify(second.controller.getSnapshot())).not.toContain('original private attempt');
    expect(JSON.stringify(second.controller.journal.getSnapshot())).not.toContain('original private attempt');
    expect(second.post).not.toHaveBeenCalled();
    await second.controller.send();
    expect(await second.post.mock.calls[0][0].clone().json()).toEqual(original);
    expect(second.controller.getSnapshot().draft).toBe('new independent text');
    expect(vault.row!.hasPending).toBe(false);
});
