test('account or pair change cannot decrypt old journal; explicit reset requires its captured confirmation', async () => {
    const vault = journalFixture(), first = session(vault.engine());
    await first.login();
    first.controller.setDraft('old pair private');
    await first.controller.journal.flush();
    first.controller.dispose();
    const second = session(vault.engine());
    second.setContext({ state: 'ready', sessionId: 'session', userId: uuid(91), coupleId: uuid(92), membershipEpoch: 1 });
    await second.login();
    await second.controller.journal.restore();
    expect(second.controller.getSnapshot().draft).toBe('');
    second.controller.setDraft('current draft');
    await second.controller.journal.flush();
    second.controller.journal.beginReset();
    const token = second.controller.journal.getSnapshot().resetToken!;
    second.controller.journal.cancelReset();
    await second.controller.journal.confirmReset(token);
    expect(second.controller.getSnapshot().draft).toBe('current draft');
    second.controller.journal.beginReset();
    await second.controller.journal.confirmReset(second.controller.journal.getSnapshot().resetToken!);
    expect(second.controller.getSnapshot().draft).toBe('');
    expect(vault.row!.sealed).toBeNull();
});
