test('discard during durable prepare waits for its commit, removes pending locally, and does not POST', async () => {
    const vault = journalFixture(), engine = vault.engine(), held = latch();
    const first = session({ ...engine, prepareSend: async (...args) => {
        const result = await engine.prepareSend(...args);
        held.arrive(); await held.gate; return result;
    } });
    await first.login(); first.controller.setDraft('discard durable attempt');
    await first.controller.journal.flush();
    const sending = first.controller.send(); await held.reached;
    first.controller.beginDiscardOutgoing();
    const confirmation = first.controller.getSnapshot().discardConfirmation!;
    const discarding = first.controller.confirmDiscardOutgoing(confirmation.token);
    first.controller.setDraft('new text survives discard');
    held.release(); await sending; await discarding;
    expect(first.post).not.toHaveBeenCalled();
    expect(vault.row!.hasPending).toBe(false);
    expect(first.controller.getSnapshot().draft).toBe('new text survives discard');
    await first.controller.journal.flush(); first.controller.dispose();
    const second = session(vault.engine()); await second.login(); await second.controller.journal.restore();
    expect(second.controller.getSnapshot().draft).toBe('new text survives discard');
    expect(second.controller.getSnapshot().outgoingPending).toBeFalsy();
});


