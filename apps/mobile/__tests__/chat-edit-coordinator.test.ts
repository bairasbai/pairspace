import { createChatEdit } from '../src/auth/chat-edit';
import { editChatMessage } from '../src/chat/edit-transport';
import { readReplyDetail } from '../src/chat/reply-transport';
import { row, uuid } from './chat-window.fixture';
jest.mock('../src/chat/edit-transport', () => ({ editChatMessage: jest.fn() }));
jest.mock('../src/chat/reply-transport', () => ({ readReplyDetail: jest.fn() }));
const edit = jest.mocked(editChatMessage), read = jest.mocked(readReplyDetail);
function fixture() {
    let available = true, cookie = 'cookie', message = row(1);
    const session = { scope: { userId: uuid(1), coupleId: uuid(2), membershipEpoch: 1, sessionId: 's' }, token: 'cookie', credentialGeneration: 1 };
    const credential = jest.fn(async (): Promise<{
        credential: typeof session;
    } | null> => ({ credential: session }));
    const accept = jest.fn(async () => true), denied = jest.fn();
    const controller = createChatEdit('https://example.test', { capture: () => available ? { generation: 1, session } : null,
        find: () => message, credential, cookie: async () => cookie, publish: jest.fn(), denied, accept }, jest.fn(), () => uuid(20), () => uuid(21));
    return { controller, credential, accept, denied, setAvailable: (v: boolean) => { available = v; }, setCookie: (v: string) => { cookie = v; }, setMessage: (v: typeof message) => { message = v; }, begin: () => controller.beginEdit(message.id) };
}
beforeEach(() => { edit.mockReset(); read.mockReset(); });
it('guards unavailable/foreign/oversized selection, blank save, cancellation, and frozen configuration', async () => {
    const f = fixture();
    f.setAvailable(false);
    f.begin();
    f.controller.setEditDraft('private');
    expect(f.controller.getSnapshot().draft).toBe('');
    f.setAvailable(true);
    f.setMessage({ ...row(1), senderId: uuid(99) });
    f.begin();
    expect(f.controller.getSnapshot().targetId).toBeUndefined();
    f.setMessage(row(1));
    f.begin();
    f.controller.setEditDraft('x'.repeat(16001));
    expect(f.controller.getSnapshot().draft).toBe(row(1).body);
    f.controller.setEditDraft('');
    await f.controller.saveEdit();
    expect(f.controller.getSnapshot().status).toBe('error');
    expect(edit).not.toHaveBeenCalled();
    f.controller.cancelEdit();
    expect(f.controller.getSnapshot().status).toBe('idle');
    await f.controller.reloadEdit();
});
it('discovery missing/throw and unknown invalid ACK retain exact command; cookie mismatch denies', async () => {
    const f = fixture();
    f.begin();
    f.controller.setEditDraft('new');
    f.credential.mockResolvedValueOnce(null);
    await f.controller.saveEdit();
    expect(f.controller.getSnapshot().status).toBe('unknown');
    f.credential.mockRejectedValueOnce(Error());
    await f.controller.retryEdit();
    expect(f.controller.getSnapshot().error).toBe('transport_error');
    edit.mockResolvedValueOnce({ ok: false, error: 'invalid_response' });
    await f.controller.retryEdit();
    expect(f.controller.getSnapshot().status).toBe('unknown');
    f.setCookie('newcookie');
    edit.mockResolvedValueOnce({ ok: false, error: 'transport_error' });
    await f.controller.retryEdit();
    expect(f.denied).toHaveBeenCalledWith('auth_required');
    f.controller.reset();
    await f.controller.retryEdit();
    expect(f.controller.getSnapshot().status).toBe('idle');
});
it('canonical refusal and invalid canonical acceptance do not masquerade as a successful save', async () => {
    const f = fixture();
    f.begin();
    f.controller.setEditDraft('new');
    f.accept.mockResolvedValue(false);
    edit.mockResolvedValueOnce({ ok: true, value: { commandId: uuid(20), replay: false, message: { ...row(1), body: 'new', version: 2, replyToId: null, deletedAt: null } } });
    await f.controller.saveEdit();
    expect(f.controller.getSnapshot()).toMatchObject({ status: 'unknown', error: 'invalid_response' });
    f.accept.mockResolvedValue(true);
    edit.mockResolvedValueOnce({ ok: false, error: 'message_deleted', message: { ...row(1), body: null, version: 3, replyToId: null, deletedAt: '2026-11-12T00:00:00.000Z' } });
    await f.controller.retryEdit();
    expect(f.controller.getSnapshot().status).toBe('deleted');
});
it('reload failures and auth failures retain unsaved draft without silent PATCH', async () => {
    const f = fixture();
    f.begin();
    f.controller.setEditDraft('private');
    read.mockResolvedValueOnce({ ok: false, error: 'reply_unavailable' });
    await f.controller.reloadEdit();
    expect(f.controller.getSnapshot()).toMatchObject({ draft: 'private', needsReload: true, error: 'reply_unavailable' });
    read.mockRejectedValueOnce(Error());
    await f.controller.reloadEdit();
    expect(f.controller.getSnapshot().error).toBe('transport_error');
    read.mockResolvedValueOnce({ ok: false, error: 'auth_required' });
    await f.controller.reloadEdit();
    expect(f.denied).toHaveBeenCalledWith('auth_required');
    f.accept.mockResolvedValue(false);
    read.mockResolvedValueOnce({ ok: true, value: { ...row(1), version: 2, replyToId: null, deletedAt: null } });
    await f.controller.reloadEdit();
    expect(f.controller.getSnapshot().error).toBe('invalid_response');
    f.setCookie('changed');
    read.mockResolvedValueOnce({ ok: false, error: 'transport_error' });
    await f.controller.reloadEdit();
    expect(f.denied).toHaveBeenCalledWith('auth_required');
    expect(edit).not.toHaveBeenCalled();
});
it('terminal canonical reload blocks saving while retaining genuinely new private text', async () => {
    const f = fixture();
    f.begin();
    f.controller.setEditDraft('new private');
    read.mockResolvedValueOnce({ ok: true, value: { ...row(1), body: null, version: 2, replyToId: null, deletedAt: '2026-11-12T00:00:00.000Z' } });
    await f.controller.reloadEdit();
    expect(f.controller.getSnapshot()).toMatchObject({ status: 'deleted', draft: 'new private' });
    await f.controller.saveEdit();
    expect(edit).not.toHaveBeenCalled();
});
it.each([true, false])('reset during edit canonical acceptance cannot publish either outcome (%s)', async (accepted) => {
    const f = fixture();
    f.begin();
    f.controller.setEditDraft('old');
    let release!: (value: boolean) => void, started!: () => void;
    const ready = new Promise<void>(resolve => { started = resolve; });
    f.accept.mockImplementationOnce(() => { started(); return new Promise(resolve => { release = resolve; }); });
    edit.mockResolvedValueOnce({ ok: true, value: { commandId: uuid(20), replay: false, message: { ...row(1), body: 'old', version: 2, replyToId: null, deletedAt: null } } });
    const save = f.controller.saveEdit();
    await ready;
    f.controller.reset();
    release(accepted);
    await save;
    expect(f.controller.getSnapshot()).toEqual({ status: 'idle', draft: '', needsReload: false });
});
it.each([true, false])('reset during reload canonical acceptance cannot publish either outcome (%s)', async (accepted) => {
    const f = fixture();
    f.begin();
    let release!: (value: boolean) => void, started!: () => void;
    const ready = new Promise<void>(resolve => { started = resolve; });
    f.accept.mockImplementationOnce(() => { started(); return new Promise(resolve => { release = resolve; }); });
    read.mockResolvedValueOnce({ ok: true, value: { ...row(1), version: 2, replyToId: null, deletedAt: null } });
    const load = f.controller.reloadEdit();
    await ready;
    f.controller.reset();
    release(accepted);
    await load;
    expect(f.controller.getSnapshot()).toEqual({ status: 'idle', draft: '', needsReload: false });
});
it('same-version observation/no-op draft cannot replace edited text; deleted new drafts stay private', async () => {
    const f = fixture();
    f.begin();
    f.controller.observe(row(1));
    f.controller.setEditDraft(row(1).body);
    f.controller.setEditDraft('unsaved');
    f.begin();
    expect(f.controller.getSnapshot().draft).toBe('unsaved');
    f.controller.observe({ ...row(1), body: null, version: 2, deletedAt: '2026-11-12T00:00:00.000Z' });
    f.controller.setEditDraft('private after deletion');
    expect(f.controller.getSnapshot()).toMatchObject({ status: 'deleted', draft: 'private after deletion' });
});
it('auth error after PATCH blocks, and reset while discovery waits never sends', async () => {
    const f = fixture();
    f.begin();
    f.controller.setEditDraft('new');
    edit.mockResolvedValueOnce({ ok: false, error: 'access_required' });
    await f.controller.saveEdit();
    expect(f.denied).toHaveBeenCalledWith('access_required');
    f.controller.reset();
    f.begin();
    let release!: (value: null) => void;
    f.credential.mockReturnValueOnce(new Promise(resolve => { release = resolve; }));
    const save = f.controller.saveEdit();
    f.controller.reset();
    release(null);
    await save;
    expect(edit).toHaveBeenCalledTimes(1);
});
