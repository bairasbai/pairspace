import { act, fireEvent, render, screen } from '@testing-library/react-native';
import { AccessibilityInfo, BackHandler } from 'react-native';
import mockSafeAreaContext from 'react-native-safe-area-context/jest/mock';
import App from '../App';
import { Showcase } from '../src/Showcase';
import { showcaseCopy } from '../src/showcaseCopy';
jest.mock('react-native-safe-area-context', () => mockSafeAreaContext);
beforeEach(() => jest.spyOn(AccessibilityInfo, 'isReduceMotionEnabled').mockResolvedValue(true));
afterEach(() => jest.restoreAllMocks());
it.each(['ru', 'en'] as const)('opens each section without claiming live data in %s', locale => {
  const t = showcaseCopy[locale];
  const open = jest.fn();
  const view = render(<Showcase section="today" locale={locale} onOpen={open} />);
  expect(screen.getByText(t.demo)).toBeTruthy();
  fireEvent.press(screen.getByRole('button', { name: new RegExp(t.letters) }));
  expect(open).toHaveBeenLastCalledWith('letters');
  fireEvent.press(screen.getByRole('button', { name: new RegExp(t.calendar) }));
  expect(open).toHaveBeenLastCalledWith('calendar');
  view.rerender(<Showcase section="together" locale={locale} onOpen={open} />);
  fireEvent.press(screen.getByRole('button', { name: new RegExp(t.memories) }));
  expect(open).toHaveBeenLastCalledWith('memories');
  for (const name of [t.checkers, t.battleship, t.support, t.wishes, t.conversations, t.films]) expect(screen.getByText(name)).toBeTruthy();
  view.rerender(<Showcase section="letters" locale={locale} onOpen={open} />);
  expect(screen.getByText(t.futureHint)).toBeTruthy();
  view.rerender(<Showcase section="calendar" locale={locale} onOpen={open} />);
  expect(screen.getByText(t.samplePlan)).toBeTruthy();
  fireEvent.press(screen.getByRole('tab', { name: t.tasks }));
  expect(screen.getByRole('tab', { name: t.tasks })).toBeSelected();
  expect(screen.getByText(t.sampleTask)).toBeTruthy();
  fireEvent.press(screen.getByRole('tab', { name: t.plans }));
  expect(screen.getByText(t.samplePlan)).toBeTruthy();
  view.rerender(<Showcase section="memories" locale={locale} onOpen={open} />);
  expect(screen.getByText(t.memoryText)).toBeTruthy();
});
it('navigates back, resets nested screens when changing tab and keeps draft', async () => {
  render(<App />); await act(async () => {});
  fireEvent.press(screen.getByRole('button', { name: /Письма/ }));
  expect(screen.getByText(showcaseCopy.ru.letterBody)).toBeTruthy();
  fireEvent.press(screen.getByRole('button', { name: 'Назад' }));
  fireEvent.press(screen.getByRole('button', { name: /Календарь и дела/ }));
  fireEvent.press(screen.getByRole('tab', { name: 'Чат' }));
  fireEvent.changeText(screen.getByLabelText('Пробный черновик'), 'Example');
  fireEvent.press(screen.getByRole('tab', { name: 'Мы' }));
  fireEvent.press(screen.getByRole('button', { name: 'Воспоминания' }));
  expect(screen.getByText(showcaseCopy.ru.memoryText)).toBeTruthy();
  fireEvent.press(screen.getByRole('tab', { name: 'Вместе' }));
  expect(screen.getByText(showcaseCopy.ru.activities)).toBeTruthy();
  fireEvent.press(screen.getByRole('tab', { name: 'Чат' }));
  expect(screen.getByDisplayValue('Example')).toBeTruthy();
});
it('keeps showcase locales equivalent', () => expect(Object.keys(showcaseCopy.ru)).toEqual(Object.keys(showcaseCopy.en)));

it('handles hardware Back only within a nested section and removes its listener', async () => {
  const remove = jest.fn();
  const listener = jest.spyOn(BackHandler, 'addEventListener').mockReturnValue({ remove });
  const view = render(<App />); await act(async () => {});
  expect(listener).not.toHaveBeenCalled();
  fireEvent.press(screen.getByRole('button', { name: /Письма/ }));
  act(() => expect(listener.mock.calls.at(-1)![1]({ type: 'hardwareBackPress', timeStamp: 0 })).toBe(true));
  expect(screen.getByText(showcaseCopy.ru.subtitle)).toBeTruthy();
  expect(remove).toHaveBeenCalledTimes(1);
  fireEvent.press(screen.getByRole('button', { name: /Письма/ }));
  view.unmount();
  expect(remove).toHaveBeenCalledTimes(2);
});

it('replaces the scroll container for nested and primary navigation', async () => {
  render(<App />); await act(async () => {});
  fireEvent.press(screen.getByRole('tab', { name: 'Вместе' }));
  const oldScroll = screen.getByTestId('screen-scroll-together');
  fireEvent.scroll(oldScroll, { nativeEvent: { contentOffset: { y: 700, x: 0 } } });
  fireEvent.press(screen.getByRole('button', { name: /Письма/ }));
  expect(oldScroll).not.toBeOnTheScreen();
  expect(screen.getByTestId('screen-scroll-letters')).toBeOnTheScreen();
  fireEvent.press(screen.getByRole('button', { name: 'Назад' }));
  expect(screen.queryByTestId('screen-scroll-letters')).toBeNull();
  expect(screen.getByTestId('screen-scroll-together')).toBeOnTheScreen();
  fireEvent.press(screen.getByRole('tab', { name: 'Сегодня' }));
  expect(screen.queryByTestId('screen-scroll-together')).toBeNull();
  expect(screen.getByTestId('screen-scroll-today')).toBeOnTheScreen();
});
