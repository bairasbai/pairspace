it('full GET clears untouched deleted editors and marks changed or deleted dirty drafts unsavable', async () => {
    const f = fixture();
    await f.load([word]);
    f.api.beginEdit(word.id);
    await f.load([deleted]);
    expect(f.api.getSnapshot().editor).toBeNull();
    const g = fixture();
    await g.load([word]);
    g.api.beginEdit(word.id);
    g.api.setEditField('meaning', 'Unsaved local');
    await g.load([{ ...word, version: 2, edited: true, meaning: 'Remote change' }]);
    expect(g.api.getSnapshot().editor).toMatchObject({ stale: 'changed', fields: { meaning: 'Unsaved local' } });
    const calls = g.operation.mock.calls.length;
    await g.api.saveEdit();
    expect(g.operation).toHaveBeenCalledTimes(calls);
    expect(g.api.getSnapshot().status).toBe('conflict');
    await g.load([{ ...deleted, version: 3 }]);
    expect(g.api.getSnapshot().editor).toMatchObject({ stale: 'deleted', fields: { meaning: 'Unsaved local' } });
    g.api.setEditField('meaning', 'Still unsaved');
    await g.api.saveEdit();
    expect(g.api.getSnapshot().editor?.fields.meaning).toBe('Still unsaved');
});
