it.each([false, true])('observed deletion scrubs unchanged editor immediately, preserves genuinely new draft=%s', async (newer) => {
    const f = fixture();
    await f.login();
    f.controller.beginEdit(row(250).id);
    f.controller.setEditDraft('pending edited text');
    const hold = deferred();
    f.edit.mockReturnValueOnce(hold.promise);
    const save = f.controller.saveEdit();
    await settle();
    if (newer)
        f.controller.setEditDraft('new unsaved text');
    const dead = { ...message(250), body: null, version: 3, deletedAt: '2026-11-12T00:00:00.000Z' };
    f.history.mockImplementationOnce(async (r) => envelope({ messages: [dead], readId: new URL(r.url).searchParams.get('read_id'), hasOlder: false, hasNewer: false, olderCursor: null, newerCursor: null }));
    await f.controller.loadLatest();
    expect(f.controller.getSnapshot().editState).toMatchObject({ status: 'deleted', draft: newer ? 'new unsaved text' : '' });
    await f.controller.retryEdit();
    expect(f.edit).toHaveBeenCalledTimes(1);
    hold.resolve(envelope({ commandId: uuid(20), replay: false, message: { ...message(250), body: 'pending edited text', version: 2 } }));
    await save;
    expect(f.controller.getSnapshot().messages[0].body).toBeNull();
    expect(JSON.stringify(f.controller.getSnapshot())).not.toContain('pending edited text');
});
it('late edit ACK after logout cannot publish into another authentication generation', async () => {
    const f = fixture();
    await f.login();
    f.controller.beginEdit(row(250).id);
    f.controller.setEditDraft('old session');
    const hold = deferred();
    f.edit.mockReturnValueOnce(hold.promise);
    const save = f.controller.saveEdit();
    await settle();
    await f.controller.signOut();
    await f.login();
    f.controller.setDraft('new session');
    hold.resolve(envelope({ commandId: uuid(20), replay: false, message: { ...message(250), body: 'old session', version: 2 } }));
    await save;
    expect(f.controller.getSnapshot().editState).toBeUndefined();
    expect(f.controller.getSnapshot().draft).toBe('new session');
});
