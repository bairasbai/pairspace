import { fixture, row, message, uuid, envelope, deferred, settle } from './chat-replies.fixture';
it('own validated edit is explicit and updates canonical window; cancel is read-only', async () => {
    const f = fixture();
    await f.login();
    f.controller.beginEdit(uuid(999));
    expect(f.controller.getSnapshot().editState).toBeUndefined();
    f.controller.beginEdit(row(250).id);
    expect(f.controller.getSnapshot().editState?.draft).toBe(row(250).body);
    f.controller.setEditDraft('edited');
    f.controller.cancelEdit();
    expect(f.edit).not.toHaveBeenCalled();
    f.controller.beginEdit(row(250).id);
    f.controller.setEditDraft('edited');
    await f.controller.saveEdit();
    expect(f.controller.getSnapshot().editState).toMatchObject({ status: 'saved', version: 2, draft: 'edited' });
    expect(f.controller.getSnapshot().messages.find(m => m.id === row(250).id)).toMatchObject({ version: 2, body: 'edited' });
    expect(await f.edit.mock.calls[0][0].clone().json()).toEqual({ membership_epoch: 1, command_id: uuid(20), expected_version: 1, body: 'edited' });
});
it('protects unsaved target draft and retries original unknown edit while preserving newer text', async () => {
    const f = fixture();
    await f.login();
    f.controller.beginEdit(row(250).id);
    f.controller.setEditDraft('first');
    f.controller.beginEdit(row(249).id);
    expect(f.controller.getSnapshot().editState?.targetId).toBe(row(250).id);
    f.edit.mockRejectedValueOnce(Error());
    await f.controller.saveEdit();
    f.controller.cancelEdit();
    f.controller.setEditDraft('new private');
    await f.controller.retryEdit();
    expect(await f.edit.mock.calls[0][0].clone().text()).toBe(await f.edit.mock.calls[1][0].clone().text());
    expect(f.controller.getSnapshot().editState).toMatchObject({ status: 'editing', draft: 'new private', version: 2 });
});
it('conflict preserves draft and requires explicit canonical reload before a new command', async () => {
    const f = fixture();
    await f.login();
    f.controller.beginEdit(row(250).id);
    f.controller.setEditDraft('my draft');
    f.edit.mockResolvedValueOnce(new Response(JSON.stringify({ ok: false, error: 'version_conflict' }), { status: 409 }));
    await f.controller.saveEdit();
    await f.controller.saveEdit();
    expect(f.edit).toHaveBeenCalledTimes(1);
    expect(f.controller.getSnapshot().editState).toMatchObject({ draft: 'my draft', needsReload: true });
    f.detail.mockImplementationOnce(async (r) => envelope({ readId: new URL(r.url).searchParams.get('read_id'), message: { ...message(250), body: 'other device', version: 2 } }));
    await f.controller.reloadEdit();
    expect(f.controller.getSnapshot().editState).toMatchObject({ draft: 'my draft', needsReload: false, version: 2 });
    await f.controller.saveEdit();
    expect((await f.edit.mock.calls[1][0].clone().json()).expected_version).toBe(2);
});
