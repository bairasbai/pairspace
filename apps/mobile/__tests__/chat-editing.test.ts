it.each([false, true])('exact create retry returns edited canonical without mutating original command; reply=%s', async (reply) => {
    const f = fixture();
    await f.login();
    if (reply)
        f.controller.setReplyTarget(row(250).id);
    f.controller.setDraft('original');
    f.post.mockRejectedValueOnce(Error());
    await f.controller.send();
    f.post.mockResolvedValueOnce(envelope({ replay: true, message: { ...row(300), clientId: uuid(20), body: 'edited elsewhere', version: 2, ...(reply ? { replyToId: row(250).id, deletedAt: null } : {}) } }));
    await f.controller.send();
    expect(f.controller.getSnapshot().outgoing).toMatchObject({ status: 'sent', body: 'edited elsewhere' });
    expect(await f.post.mock.calls[0][0].clone().text()).toBe(await f.post.mock.calls[1][0].clone().text());
});
